def _whisker_outliers(by_group: pd.DataFrame) -> list[tuple[str, float]]:
    """List ``(group, height)`` for every point beyond a box plot whisker (the 1.5 x IQR rule on linear-interpolated quartiles)."""
    outliers = []
    for group, column in zip(GROUP_NAMES, GROUP_HEIGHT_COLUMNS, strict=True):
        values = by_group[column].to_numpy(dtype=float)
        q1, q3 = np.percentile(values, [25, 75])
        low, high = q1 - 1.5 * (q3 - q1), q3 + 1.5 * (q3 - q1)
        outliers.extend((group, float(value)) for value in values if value < low or value > high)
    return outliers


def create_note_values(
    measurements: pd.DataFrame,
    *,
    pearson_results: dict[tuple[str, str], StatTestResult],
    spearman_results: dict[tuple[str, str], StatTestResult],
    matrix: pd.DataFrame,
) -> dict[str, str]:
    """Compute every number that the notes quote about the class, formatted as the notes print it.

    Args:
        measurements: The class table.
        pearson_results: Pearson results by column pair, as stored in the project.
        spearman_results: Spearman results by column pair, as stored in the project.
        matrix: The correlation matrix table.

    Returns:
        Values for the ``{placeholders}`` of the note templates.

    Raises:
        ValueError: When a claim the notes make about the data (one age mode, one box plot outlier) does not hold.
    """
    heights = measurements[HEIGHT].to_numpy(dtype=float)
    mean, sd = float(heights.mean()), float(heights.std(ddof=1))
    low, high = mean - sd, mean + sd
    within = int(((heights >= low) & (heights <= high)).sum())

    descriptive = DescriptiveStatsEngine.describe([measurements[HEIGHT]]).to_dataframe()
    by_group = create_height_by_group(measurements)
    group_medians = DescriptiveStatsEngine.describe([by_group[column] for column in GROUP_HEIGHT_COLUMNS]).to_dataframe()

    modes = measurements[AGE].mode()
    if len(modes) != 1:
        raise ValueError("The notes assume that age has exactly one mode.")
    age_mode = modes.item()

    outliers = _whisker_outliers(by_group)
    if len(outliers) != 1:
        raise ValueError("The notes assume exactly one point beyond the box plot whiskers.")
    outlier_group, outlier_height = outliers[0]
    outlier_rows = measurements[(measurements["Group"] == outlier_group) & (measurements[HEIGHT] == outlier_height)]
    if len(outlier_rows) != 1:
        raise ValueError("The notes assume that the box plot outlier is exactly one student.")

    height_weight, height_sleep = pearson_results[(HEIGHT, WEIGHT)], pearson_results[(HEIGHT, SLEEP)]
    age_height = spearman_results[(AGE, HEIGHT)]
    r_hw, r_hs = height_weight.statistic, height_sleep.statistic
    coin_count = 2 * sum(math.comb(COIN_TOSSES, k) for k in range(COIN_TOSSES - 1, COIN_TOSSES + 1))
    result_rows = {"hw": dict(height_weight.rows), "hs": dict(height_sleep.rows), "ah": dict(age_height.rows)}
    sleep_count = int(_panel_value(DescriptiveStatsEngine.describe([measurements[SLEEP]]).to_dataframe(), "Count", SLEEP))

    return {
        "student_count": str(len(measurements)),
        "per_group": str(int((measurements["Group"] == GROUP_NAMES[0]).sum())),
        "sleep_missing": str(int(measurements[SLEEP].isna().sum())),
        "sleep_count": str(sleep_count),
        "pairs_sleep": str(result_rows["hs"]["N pairs"]),
        "h_mean": _panel_value(descriptive, "Mean", HEIGHT),
        "h_median": _panel_value(descriptive, "Median (Q2)", HEIGHT),
        "h_sd": _panel_value(descriptive, "Std. deviation", HEIGHT),
        "h_min": _panel_value(descriptive, "Minimum", HEIGHT),
        "h_max": _panel_value(descriptive, "Maximum", HEIGHT),
        "h_mean_1": f"{mean:.1f}",
        "h_sd_1": f"{sd:.1f}",
        "h_low": f"{low:.1f}",
        "h_high": f"{high:.1f}",
        "within_count": str(within),
        "within_pct": f"{100 * within / len(heights):.1f}",
        "med_a": _panel_value(group_medians, "Median (Q2)", GROUP_HEIGHT_COLUMNS[0]),
        "med_b": _panel_value(group_medians, "Median (Q2)", GROUP_HEIGHT_COLUMNS[1]),
        "med_c": _panel_value(group_medians, "Median (Q2)", GROUP_HEIGHT_COLUMNS[2]),
        "outlier_height": f"{outlier_height:g}",
        "outlier_group": outlier_group,
        "outlier_student": str(outlier_rows["Student"].item()),
        "age_mode": str(age_mode),
        "age_mode_count": str(int((measurements[AGE] == age_mode).sum())),
        "age_bins": str(AGE_BINS),
        "r_hw": f"{r_hw:.2f}",
        "strength_hw": str(result_rows["hw"]["Strength"]),
        "r2_hw": f"{r_hw * r_hw:.0%}",
        "r_hs": f"{r_hs:.2f}",
        "strength_hs": str(result_rows["hs"]["Strength"]),
        "p_hw": str(result_rows["hw"]["p-value"]),
        "p_hs": str(result_rows["hs"]["p-value"]),
        "p_hs_short": f"{height_sleep.p_value:.2f}",
        "rho_ah": f"{age_height.statistic:.2f}",
        "p_ah": str(result_rows["ah"]["p-value"]),
        "strength_ah": str(result_rows["ah"]["Strength"]),
        "r_ws": f"{matrix.loc[matrix['Variable'] == WEIGHT, SHOE_SIZE].item():.2f}",
        "coin_count": str(coin_count),
        "coin_p": f"{coin_count / 2**COIN_TOSSES:.2g}",
        "open_class": OPEN_STEP.format(dataset=MEASUREMENTS_NAME),
        "open_by_group": OPEN_STEP.format(dataset=HEIGHT_BY_GROUP_NAME),
    }



SEED = 35
AGE_BINS = 5  # ages 14 to 18: one bar per whole age
STUDENT_COUNT = 120
GROUP_NAMES = ("A", "B", "C")
GROUP_MEAN_HEIGHTS_CM = {"A": 160.0, "B": 165.0, "C": 170.0}

MEASUREMENTS_NAME = "Class measurements"
HEIGHT_BY_GROUP_NAME = "Height by group"
CORRELATION_MATRIX_NAME = "Correlation matrix (Pearson r)"

AGE = "Age (years)"
HEIGHT = "Height (cm)"
WEIGHT = "Weight (kg)"
SHOE_SIZE = "Shoe size (EU)"
SLEEP = "Hours of sleep"
NUMERIC_COLUMNS = (AGE, HEIGHT, WEIGHT, SHOE_SIZE, SLEEP)
GROUP_HEIGHT_COLUMNS = tuple(f"Group {group} (cm)" for group in GROUP_NAMES)

PEARSON_PAIRS = ((HEIGHT, WEIGHT), (HEIGHT, SLEEP))
SPEARMAN_PAIRS = ((AGE, HEIGHT),)


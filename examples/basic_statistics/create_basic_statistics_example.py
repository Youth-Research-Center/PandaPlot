def create_class_measurements() -> pd.DataFrame:
    """Generate the 120-row synthetic class table from a fixed seed.

    Returns:
        Columns Student (text), Group, Age (years), Height (cm), Weight (kg), Shoe size (EU) and Hours of sleep.
    """
    rng = np.random.default_rng(SEED)
    per_group = STUDENT_COUNT // len(GROUP_NAMES)
    groups = rng.permutation(np.repeat(GROUP_NAMES, per_group))
    age = rng.choice([14, 15, 16, 17, 18], size=STUDENT_COUNT, p=[0.1, 0.2, 0.4, 0.2, 0.1])
    height = rng.normal([GROUP_MEAN_HEIGHTS_CM[group] for group in groups], 7.0).round(1)
    weight = (62.0 + 0.85 * (height - 165.0) + rng.normal(0.0, 7.5, STUDENT_COUNT)).round(1)
    shoe_size = np.rint(40.0 + 0.3 * (height - 165.0) + rng.normal(0.0, 1.7, STUDENT_COUNT)).astype(np.int64)
    sleep = rng.normal(8.0, 0.8, STUDENT_COUNT).round(1)
    sleep[rng.choice(STUDENT_COUNT, size=2, replace=False)] = np.nan
    return pd.DataFrame(
        {
            "Student": [f"S{number:03d}" for number in range(1, STUDENT_COUNT + 1)],
            "Group": groups,
            AGE: age.astype(np.int64),
            HEIGHT: height,
            WEIGHT: weight,
            SHOE_SIZE: shoe_size,
            SLEEP: sleep,
        }
    )


def create_height_by_group(measurements: pd.DataFrame) -> pd.DataFrame:
    """Return the heights of each group as one column per group, in student order."""
    return pd.DataFrame(
        {
            column: measurements.loc[measurements["Group"] == group, HEIGHT].reset_index(drop=True)
            for group, column in zip(GROUP_NAMES, GROUP_HEIGHT_COLUMNS, strict=True)
        }
    )


def create_correlation_matrix(measurements: pd.DataFrame) -> pd.DataFrame:
    """Build the Pearson correlation table with the Statistical Tests engine, one pair at a time.

    Returns:
        A ``Variable`` text column plus one float column per variable, in the same order.
    """
    matrix: dict[str, list[float]] = {name: [] for name in NUMERIC_COLUMNS}
    for row_name in NUMERIC_COLUMNS:
        for column_name in NUMERIC_COLUMNS:
            if row_name == column_name:
                matrix[column_name].append(1.0)
                continue
            result = StatsEngine.run_test(StatTestType.PEARSON, [measurements[row_name], measurements[column_name]])
            matrix[column_name].append(round(float(result.statistic), 3))
    return pd.DataFrame({"Variable": list(NUMERIC_COLUMNS), **matrix})



def create_project_data_manager() -> ProjectDataManager:
    """Create a manager capable of saving every item type used here."""
    factory = ItemDataManagerFactory()
    for name, item_class, manager in (
        ("note", Note, NoteDataManager()),
        ("folder", Folder, FolderDataManager()),
        ("chart", Chart, ChartDataManager()),
        ("dataset", Dataset, DatasetDataManager()),
    ):
        factory.register(type_name=name, item_class=item_class, manager=manager, extension=name)
    return ProjectDataManager(factory)


def create_class_measurements() -> pd.DataFrame:
    """Generate the 120-row synthetic class table from a fixed seed.

    Returns:
        Columns Student (text), Group, Age (years), Height (cm), Weight (kg), Shoe size (EU) and Hours of sleep.
    """
    rng = np.random.default_rng(SEED)
    per_group = STUDENT_COUNT // len(GROUP_NAMES)
    groups = rng.permutation(np.repeat(GROUP_NAMES, per_group))
    age = rng.choice([14, 15, 16, 17, 18], size=STUDENT_COUNT, p=[0.1, 0.2, 0.4, 0.2, 0.1])
    height = rng.normal([GROUP_MEAN_HEIGHTS_CM[group] for group in groups], 7.0).round(1)
    weight = (62.0 + 0.85 * (height - 165.0) + rng.normal(0.0, 7.5, STUDENT_COUNT)).round(1)
    shoe_size = np.rint(40.0 + 0.3 * (height - 165.0) + rng.normal(0.0, 1.7, STUDENT_COUNT)).astype(np.int64)
    sleep = rng.normal(8.0, 0.8, STUDENT_COUNT).round(1)
    sleep[rng.choice(STUDENT_COUNT, size=2, replace=False)] = np.nan
    return pd.DataFrame(
        {
            "Student": [f"S{number:03d}" for number in range(1, STUDENT_COUNT + 1)],
            "Group": groups,
            AGE: age.astype(np.int64),
            HEIGHT: height,
            WEIGHT: weight,
            SHOE_SIZE: shoe_size,
            SLEEP: sleep,
        }
    )


def create_height_by_group(measurements: pd.DataFrame) -> pd.DataFrame:
    """Return the heights of each group as one column per group, in student order."""
    return pd.DataFrame(
        {
            column: measurements.loc[measurements["Group"] == group, HEIGHT].reset_index(drop=True)
            for group, column in zip(GROUP_NAMES, GROUP_HEIGHT_COLUMNS, strict=True)
        }
    )


def create_correlation_matrix(measurements: pd.DataFrame) -> pd.DataFrame:
    """Build the Pearson correlation table with the Statistical Tests engine, one pair at a time.

    Returns:
        A ``Variable`` text column plus one float column per variable, in the same order.
    """
    matrix: dict[str, list[float]] = {name: [] for name in NUMERIC_COLUMNS}
    for row_name in NUMERIC_COLUMNS:
        for column_name in NUMERIC_COLUMNS:
            if row_name == column_name:
                matrix[column_name].append(1.0)
                continue
            result = StatsEngine.run_test(StatTestType.PEARSON, [measurements[row_name], measurements[column_name]])
            matrix[column_name].append(round(float(result.statistic), 3))
    return pd.DataFrame({"Variable": list(NUMERIC_COLUMNS), **matrix})


def _build_series(chart: Chart, dataset: Dataset, *, x_column: str | None, y_column: str, label: str, **style_options: Any) -> None:
    """Add one series reading ``y_column`` (and ``x_column`` when given) of ``dataset`` to ``chart``."""
    chart.add_data_series(
        dataset_id=dataset.id,
        x_column_id=(dataset.column_id(x_column) or "") if x_column else "",
        y_column_id=dataset.column_id(y_column) or "",
        x_column=x_column or "",
        y_column=y_column,
        label=label,
        style=build_series_style(chart.chart_type.value, **style_options),
    )


def _new_chart(name: str, chart_type: str, *, title: str, x_label: str = "", y_label: str = "") -> Chart:
    chart = Chart(name=name, chart_type=chart_type)
    chart.config.title = title
    chart.config.x.label = x_label
    chart.config.y.label = y_label
    return chart


_GROUP_COLORS = ("#1f77b4", "#ff7f0e", "#2ca02c")


def create_project(measurements: pd.DataFrame | None = None) -> Project:
    """Build the in-memory Basic Statistics project (not yet saved)."""
    measurements = create_class_measurements() if measurements is None else measurements
    project = Project(name="Basic Statistics", description=EXAMPLE_DESCRIPTION)

    start_note = Note(name="Start here", content=START_NOTE_CONTENT)
    project.add_item(start_note)

    data = Dataset(name=MEASUREMENTS_NAME, data=measurements)
    by_group = Dataset(name=HEIGHT_BY_GROUP_NAME, data=create_height_by_group(measurements))
    project.add_item(data)
    project.add_item(by_group)

    # Results are built the way the panels build them (engine output, default options) and sit at the project root.
    descriptive = DescriptiveStatsEngine.describe([measurements[name] for name in NUMERIC_COLUMNS])
    project.add_item(Dataset(name=descriptive.result_name(), data=descriptive.to_dataframe()))
    project.add_item(Note(name=descriptive.report_name(), content=descriptive.report()))
    pearson_results = {}
    for pair in PEARSON_PAIRS:
        result = StatsEngine.run_test(StatTestType.PEARSON, [measurements[name] for name in pair])
        pearson_results[pair] = result
        project.add_item(Dataset(name=result.result_name(), data=result.to_dataframe()))
    for pair in SPEARMAN_PAIRS:
        result = StatsEngine.run_test(StatTestType.SPEARMAN, [measurements[name] for name in pair])
        project.add_item(Dataset(name=result.result_name(), data=result.to_dataframe()))
    project.add_item(Dataset(name=CORRELATION_MATRIX_NAME, data=create_correlation_matrix(measurements)))

    folders = {}
    for title, content in (
        ("1 Descriptive statistics", DESCRIPTIVE_NOTE_CONTENT),
        ("2 Histograms", HISTOGRAM_NOTE_CONTENT),
        ("3 Box plots", BOX_NOTE_CONTENT),
        ("4 Correlation", CORRELATION_NOTE_CONTENT),
    ):
        folder = Folder(name=title)
        project.add_item(folder)
        project.add_item(Note(name=title, content=content), folder.id)
        folders[title] = folder
    project.add_item(Note(name="5 Try it yourself", content=EXERCISES_NOTE_CONTENT))

    height_histogram = _new_chart("Height (cm)", "hist", title="Heights of 120 students", x_label=HEIGHT, y_label="Number of students")
    _build_series(height_histogram, data, x_column=None, y_column=HEIGHT, label=HEIGHT, color="#1f77b4")
    age_histogram = _new_chart("Age (years)", "hist", title="Ages of 120 students", x_label=AGE, y_label="Number of students")
    age_histogram.config.hist_bins = AGE_BINS
    _build_series(age_histogram, data, x_column=None, y_column=AGE, label=AGE, color="#2ca02c")
    for chart in (height_histogram, age_histogram):
        project.add_item(chart, folders["2 Histograms"].id)

    box = _new_chart("Height by group", "box", title="Height by group", y_label=HEIGHT)
    for column, color in zip(GROUP_HEIGHT_COLUMNS, _GROUP_COLORS, strict=True):
        _build_series(box, by_group, x_column=None, y_column=column, label=column.removesuffix(" (cm)"), color=color)
    project.add_item(box, folders["3 Box plots"].id)

    r_weight = pearson_results[(HEIGHT, WEIGHT)].statistic
    height_weight = _new_chart("Height vs Weight", "scatter", title=f"Height vs Weight (r = {r_weight:.2f})", x_label=HEIGHT, y_label=WEIGHT)
    _build_series(height_weight, data, x_column=HEIGHT, y_column=WEIGHT, label="Students", color="#1f77b4")
    r_sleep = pearson_results[(HEIGHT, SLEEP)].statistic
    height_sleep = _new_chart(
        "Height vs Hours of sleep", "scatter", title=f"Height vs Hours of sleep (r = {r_sleep:.2f})", x_label=HEIGHT, y_label=SLEEP,
    )
    _build_series(height_sleep, data, x_column=HEIGHT, y_column=SLEEP, label="Students", color="#d62728")
    for chart in (height_weight, height_sleep):
        project.add_item(chart, folders["4 Correlation"].id)

    project.example_info = ExampleInfo(
        is_example=True,
        summary=EXAMPLE_SUMMARY,
        section=ExampleSection.ANALYSING_DATA,
        level=ExampleLevel.BEGINNER,
        tag_ids=("statistics", "descriptive_statistics", "statistical_tests", "charts"),
        featured_chart_ids=(height_histogram.id, box.id, height_weight.id),
        start_note_id=start_note.id,
        data_credit=DATA_CREDIT,
    )
    return project


def create_basic_statistics_project(output_directory: Path | None = None) -> Path:
    """Build the Basic Statistics project, save it and return the path of the .pplot file.

    Args:
        output_directory: Where to save ``basic_statistics.pplot``; defaults to this script's folder.

    Returns:
        Path of the saved project file.
    """
    output_directory = Path(output_directory) if output_directory is not None else Path(__file__).resolve().parent
    output_directory.mkdir(parents=True, exist_ok=True)
    path = output_directory / "basic_statistics.pplot"
    create_project_data_manager().save(create_project(), str(path))
    print(f"Saved project: {path}")
    return path


if __name__ == "__main__":
    create_basic_statistics_project()

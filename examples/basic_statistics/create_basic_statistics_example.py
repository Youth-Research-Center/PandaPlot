REAL_NOTE_CONTENT = """\
# Is it real? p-values, Pearson or Spearman, causation

## The question

Even if two columns have nothing to do with each other, a sample's r is almost never exactly 0. Chance moves it a little. \
So the real question is: is the r we see big enough that chance alone is an unlikely explanation?

## The null hypothesis (H0)

A test starts by assuming the boring answer. For Pearson correlation it is: among all students like these, there is no \
straight-line trend between the two columns (r = 0). This starting assumption is the **null hypothesis**, written **H0**. \
The **H0** row of the result reads "no linear correlation (r = 0)". "Linear" means straight-line. For Spearman, the row reads \
"no monotonic correlation (rho = 0)".

## The p-value

The **p-value** answers one question: if there really were no trend, how often would a correlation at least this far from 0 \
appear by chance alone? A small p-value means chance alone would rarely do it, so it is evidence of a trend. A large p-value means \
chance does it easily.

A coin makes this concrete. Suppose you toss a coin 10 times and at least 9 tosses land on the same side. Is the coin unfair? \
If it is fair, there are 1024 equally likely sequences of 10 tosses, and {coin_count} of them have at least 9 tosses on the same \
side (9 or 10 heads, or 9 or 10 tails). So chance alone gives this in {coin_count} out of 1024 cases, which is about {coin_p}. \
That is the p-value. It counts both directions, which is what **Alternative:** two-sided does in the panel.

## Compare p with α

The **significance level**, **Significance (α):**, is the line you draw before you look at p. The usual choice, and the \
panel's default, is 0.05.

- p below α: the result says **Reject H0**. There is evidence of a trend.
- p at or above α: the result says **Fail to reject H0**. There is not enough evidence of a trend.

"Fail to reject" does not prove that there is no trend. With few students, a real trend can hide in the noise.

## Reading the Conclusion row

The **Conclusion** row starts either "Reject H0 (p = ... < 0.05): evidence that ..." or "Fail to reject H0 (p = ... >= 0.05): \
no significant evidence that ...". The signs mean "is less than" and "is greater than or equal to".

Very small p-values are written in e-notation. The number after "e-" says how many places the decimal point moves to the left, \
so 5e-2 is 0.05 and 2.5e-3 is 0.0025. The panel shows p-values as 6 decimals, or in e-notation when p is below 0.0001.

## In this class

- **Height vs Weight**: p = {p_hw}. That is a number with many zeros after the decimal point, far below 0.05. The result \
is **Reject H0**: evidence of a straight-line trend.
- **Height vs Hours of sleep**: p = {p_hs} (about {p_hs_short}). That is above 0.05, so the result is **Fail to reject H0**: \
not enough evidence of a trend. This agrees with the tiny r = {r_hs}.

## A small p is not a strong relationship

The p-value depends on how many students you have as well as on r. With many students, even a tiny r can give a tiny p. So p tells \
you how sure you can be that a trend exists, not how big it is. To judge the size, look at r, **Strength** and **R-squared**.

## Pearson or Spearman?

**Pearson correlation** looks for a straight-line trend using the actual values. A single extreme value can pull it a lot.

**Spearman correlation (rank)** first replaces each value by its **rank**: 1 for the smallest, 2 for the next, and so on. \
Then it correlates the ranks. So it finds any steadily rising or falling pattern, which is called a **monotonic** trend, even if \
the pattern curves. It is less affected by outliers, and it works for ranked data such as ratings from 1 to 5.

Example: x = 1, 2, 3, 4, 5 and y = 1, 4, 9, 16, 25. The y values always rise, but along a curve. Spearman gives exactly 1. \
Pearson gives a little less (about 0.98), because the curve is not a straight line.

Which one to choose? Look at the scatter plot first. If the dots follow a straight line and there are no wild outliers, use \
Pearson. If the trend curves but always goes the same way, or there are outliers, or the data are ranks, use Spearman. \
If you are not sure, run both.

The bundled **Spearman rank correlation [Age (years), Height (cm)]** gives rho = {rho_ah} and p = {p_ah}. That is a {strength_ah} \
correlation and the result is **Fail to reject H0**. In this synthetic class, age was generated independently of height. Real \
teenagers would show a positive trend, because older students are taller on average. A result describes the data you have.

## Correlation is not causation

Two things can move together without one causing the other. Ice-cream sales and sunburn cases both rise on sunny days. \
Ice cream does not cause sunburn. The sun causes both. A third factor can create a correlation.

This class has an example. Weight and shoe size do not affect each other, yet r = {r_ws} for them in \
**Correlation matrix (Pearson r)**. Both depend on height. A correlation only says that two columns move together. It does not \
say why, and it does not say what would happen if you changed one value.

## Common mistakes

- Thinking that p is the probability that H0 is true. It is not. It assumes H0 is true and asks how surprising the data are.
- Treating 0.05 as a magic line. A p of 0.049 and a p of 0.051 are almost the same evidence.
- Reading "Fail to reject H0" as "there is no relationship".
- Reading a small p as a strong relationship.
- Reading a correlation as a cause.
"""


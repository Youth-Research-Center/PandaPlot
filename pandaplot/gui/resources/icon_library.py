"""Bundled vector icons: loads the committed ``icon_bundle.json`` and renders theme-tinted ``QIcon``s.

The bundle is generated by ``scripts/icons/build_icon_bundle.py`` from ``icons/icon_manifest.toml``; the app never
downloads icons. To add an icon, edit the manifest and rerun the script (see AGENTS.md).
"""

import json
from functools import lru_cache
from pathlib import Path

from PySide6.QtCore import QByteArray, QRectF
from PySide6.QtGui import QColor, QGuiApplication, QIcon, QPainter, QPixmap
from PySide6.QtSvg import QSvgRenderer

_BUNDLE_PATH = Path(__file__).parent / "icons" / "icon_bundle.json"
_MANIFEST_HINT = "pandaplot/gui/resources/icons/icon_manifest.toml"


@lru_cache(maxsize=1)
def _load_bundle() -> dict:
    return json.loads(_BUNDLE_PATH.read_text(encoding="utf-8"))


def icon_svg(name: str, *, weight: str = "regular") -> str:
    """Return the bundled SVG markup of an icon (it uses ``currentColor`` for tinting).

    Args:
        name: Icon name as listed in ``icon_manifest.toml``.
        weight: Icon weight; only weights listed in the manifest are bundled.

    Raises:
        KeyError: If the icon or weight is not in the bundle.
    """
    icons = _load_bundle()["icons"]
    if name not in icons:
        raise KeyError(f"Icon '{name}' is not bundled; add it to {_MANIFEST_HINT} and run scripts/icons/build_icon_bundle.py")
    weights = icons[name]["weights"]
    if weight not in weights:
        raise KeyError(f"Icon '{name}' has no '{weight}' weight; bundled weights: {', '.join(sorted(weights))}")
    return weights[weight]


def icon_attributions() -> list[str]:
    """Return one attribution line per icon library in the bundle, e.g. ``"Phosphor Icons 2.1.1 (MIT)"``."""
    sources = _load_bundle()["sources"]
    return [f"{meta['title']} {meta['version']} ({meta['license']})" for _, meta in sorted(sources.items())]


def _device_pixel_ratio() -> float:
    screen = QGuiApplication.primaryScreen()
    return screen.devicePixelRatio() if screen is not None else 1.0


@lru_cache(maxsize=512)
def _render_pixmap(name: str, color: str, size: int, weight: str, ratio: float) -> QPixmap:
    """Render one tinted icon pixmap; results are cached by every argument, so a new colour or pixel ratio renders again.

    The cached pixmap is shared between icons (``QPixmap`` is implicitly shared) and must not be painted on by callers.
    """
    tint = QColor(color)
    if not tint.isValid():
        raise ValueError(f"Invalid icon colour: {color!r}")
    svg = icon_svg(name, weight=weight).replace("currentColor", tint.name())
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pixmap = QPixmap(round(size * ratio), round(size * ratio))
    pixmap.setDevicePixelRatio(ratio)
    pixmap.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pixmap)
    renderer.render(painter, QRectF(0, 0, size, size))
    painter.end()
    return pixmap


def clear_icon_cache() -> None:
    """Drop every cached icon render, e.g. after the primary screen's pixel ratio changed or between tests."""
    _render_pixmap.cache_clear()


def build_icon(
    name: str,
    color: str,
    *,
    size: int = 20,
    weight: str = "regular",
    disabled_color: str | None = None,
    selected_color: str | None = None,
) -> QIcon:
    """Render a bundled icon tinted with ``color`` (and optionally a different colour when disabled).

    Every call returns a new ``QIcon``; the pixmaps behind it come from a cache keyed by name, colour, size, weight and pixel ratio.

    Args:
        name: Icon name as listed in ``icon_manifest.toml``.
        color: Any colour ``QColor`` understands (theme tokens are ``#rrggbb`` strings).
        size: Logical pixel size of the square icon.
        weight: Icon weight.
        disabled_color: Colour used for ``QIcon.Mode.Disabled``; Qt greys the icon itself when omitted.
        selected_color: Colour used for ``QIcon.Mode.Selected`` (icons on a selected row); Qt derives it when omitted.

    Raises:
        KeyError: If the icon or weight is not bundled.
        ValueError: If a colour is invalid.
    """
    ratio = _device_pixel_ratio()
    icon = QIcon()
    icon.addPixmap(_render_pixmap(name, color, size, weight, ratio), QIcon.Mode.Normal)
    if disabled_color is not None:
        icon.addPixmap(_render_pixmap(name, disabled_color, size, weight, ratio), QIcon.Mode.Disabled)
    if selected_color is not None:
        icon.addPixmap(_render_pixmap(name, selected_color, size, weight, ratio), QIcon.Mode.Selected)
    return icon
